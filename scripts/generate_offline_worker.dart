// scripts/generate_offline_worker.dart
// Generates a fully functional Service Worker to replace Flutter's deprecated dummy worker.

import 'dart:io';

void main() async {
  final buildDir = Directory('build/web');
  if (!buildDir.existsSync()) {
    stderr.writeln(
      'Error: build/web directory not found. Run flutter build web first.',
    );
    exit(1);
  }

  // 1. Get version from pubspec.yaml
  final pubspecFile = File('pubspec.yaml');
  String version = '1.0.0';
  if (pubspecFile.existsSync()) {
    final lines = pubspecFile.readAsLinesSync();
    for (final line in lines) {
      if (line.trim().startsWith('version:')) {
        version = line.split(':').last.trim();
        break;
      }
    }
  }

  // Create cache name with timestamp to ensure uniqueness per build
  final cacheName =
      'adhkar-gaza-v$version-${DateTime.now().millisecondsSinceEpoch}';

  // 2. Find all files to cache
  final List<String> filesToCache = [
    '/',
    '/index.html',
    '/manifest.json',
    '/favicon.png',
  ];

  final entities = buildDir.listSync(recursive: true);
  for (final entity in entities) {
    if (entity is File) {
      // Normalize path for web
      String relativePath = entity.path
          .replaceFirst(buildDir.path, '')
          .replaceAll(r'\', '/');

      // Skip the service worker itself, maps, config files, and hidden files
      if (relativePath.endsWith('/flutter_service_worker.js') ||
          relativePath.endsWith('.map') ||
          relativePath.endsWith('_headers') ||
          relativePath.split('/').last.startsWith('.')) {
        continue;
      }

      if (!filesToCache.contains(relativePath) &&
          relativePath != '/index.html' &&
          relativePath != '/manifest.json' &&
          relativePath != '/favicon.png') {
        filesToCache.add(relativePath);
      }
    }
  }

  // 3. Generate the Custom Service Worker over the Flutter Dummy Worker
  final swContent =
      '''
// GENERATED BY scripts/generate_offline_worker.dart
const CACHE_NAME = '$cacheName';
const RESOURCES = [
  ${filesToCache.map((f) => "'$f'").join(',\n  ')}
];

self.addEventListener('install', (event) => {
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      // Using Promise.allSettled to ensure one failure doesn't crash the whole cache installation
      return Promise.all(RESOURCES.map(url => {
        return fetch(url).then(response => {
          if (!response.ok) {
            throw new Error(`Failed to fetch \${url}`);
          }
          return cache.put(url, response);
        }).catch(err => {
          console.error(`Cache install error for \${url}:`, err);
        });
      }));
    })
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((name) => {
          if (name !== CACHE_NAME) {
            console.log('Deleting old cache:', name);
            return caches.delete(name);
          }
        })
      );
    }).then(() => {
      return self.clients.claim();
    })
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') {
    return;
  }

  // Bypass non-HTTP requests (e.g., chrome-extension://) to prevent Cache API TypeError
  if (!event.request.url.startsWith('http')) {
    return;
  }

  // Bypass Kaspersky and other known external injected scripts to prevent noisy CSP console errors
  if (event.request.url.includes('kaspersky-labs.com')) {
    return;
  }

  // Network-First strategy for JSON data (adhkar, manifests, etc)
  if (event.request.url.endsWith('.json')) {
    event.respondWith(
      fetch(event.request, { cache: 'no-store' }).then((networkResponse) => {
        if (networkResponse && networkResponse.status === 200) {
          const responseToCache = networkResponse.clone();
          caches.open(CACHE_NAME).then((cache) => {
            cache.put(event.request, responseToCache).catch(e => console.warn('Cache put error:', e));
          });
        }
        return networkResponse;
      }).catch((err) => {
        console.warn('Network-first fetch failed for JSON (CSP or offline):', event.request.url, err);
        return caches.match(event.request).then((cachedResponse) => {
          if (cachedResponse) return cachedResponse;
          // If neither network nor cache has it, return a safe dummy response to prevent TypeError
          return new Response('{}', { 
            status: 408, 
            statusText: 'No network and no cache available',
            headers: { 'Content-Type': 'application/json' }
          });
        });
      })
    );
    return;
  }

  // Cache-first strategy for standard assets
  event.respondWith(
    caches.match(event.request).then((response) => {
      if (response) {
        return response;
      }
      return fetch(event.request).then((networkResponse) => {
        // Do not cache opaque responses or errors to avoid confusing offline behavior
        if (!networkResponse || networkResponse.status !== 200 || networkResponse.type !== 'basic') {
          return networkResponse;
        }
        
        const responseToCache = networkResponse.clone();
        caches.open(CACHE_NAME).then((cache) => {
          cache.put(event.request, responseToCache).catch(e => console.warn('Cache put error:', e));
        });
        
        return networkResponse;
      }).catch((error) => {
        // Log the error silently for debugging but do not crash the promise chain
        console.warn('Network fetch failed (possibly blocked by CSP or offline):', event.request.url, error);
        
        // Offline fallback for navigation requests
        if (event.request.mode === 'navigate') {
          return caches.match('/index.html');
        }
        
        // Return a generic fallback Response for blocked files so the browser doesn't throw a TypeError
        return new Response('', { status: 408, statusText: 'Request Timeout or Blocked' });
      });
    })
  );
});

// ── Web Push Event Handler ──────────────────────────────────────────────────
self.addEventListener('push', (event) => {
  let data = { title: 'أذكار غزة', body: 'حان وقت الأذكار', category: '' };
  
  try {
    if (event.data) {
      data = event.data.json();
    }
  } catch (e) {
    console.error('Push data parse error:', e);
  }

  const options = {
    body: data.body,
    data: { category: data.category || '' },
    icon: '/icons/Icon-192.png',
    badge: '/icons/Icon-192.png',
    tag: 'adhkar_' + (data.category || 'general') + '_' + Date.now(),
    requireInteraction: true,
    vibrate: [200, 100, 200],
  };

  event.waitUntil(
    self.registration.showNotification(data.title, options)
  );
});

// ── Immediate Notification via postMessage (for test button) ────────────────
self.addEventListener('message', (event) => {
  if (!event.data) return;
  const data = event.data;
  if (data.action === 'show_immediate_notification') {
    if (self.registration) {
      self.registration.showNotification(data.title, {
        body: data.body,
        data: { category: data.category },
        icon: '/icons/Icon-192.png',
        badge: '/icons/Icon-192.png',
        tag: 'adhkar_immediate_' + Date.now(),
        requireInteraction: true,
      }).catch(err => console.error('Error showing immediate notification:', err));
    }
  }
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();

  const category = event.notification.data ? event.notification.data.category : '';
  const url = category && category !== 'test' ? '/?category=' + category : '/';

  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      // Focus existing window client if matching origin
      for (const client of clientList) {
        if (client.url.includes(self.location.origin)) {
          return client.navigate(url).then(c => c.focus());
        }
      }
      // Or open a new window
      if (self.clients.openWindow) {
        return self.clients.openWindow(url);
      }
    })
  );
});
''';

  final swFile = File('build/web/flutter_service_worker.js');
  await swFile.writeAsString(swContent);
  stdout.writeln(
    '✅ Generated Custom Offline Service Worker with ${filesToCache.length} resources. Cache ID: $cacheName',
  );
}
